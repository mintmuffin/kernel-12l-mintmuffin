#!/usr/bin/env bash
#
# package.sh - turn a finished kernel build into flashable artifacts.
#
#   AnyKernel3 zip  (recommended: keeps the device's own boot image layout)
#   boot.img        (standalone, stock PE12 ramdisk baked in)
#   Odin tar        (boot.img inside a tar, for Odin "AP")
#
# Usage:
#   scripts/package.sh --kernel-dir <tree> --device starlte [--out dist]
#                      [--tag pe12-bakasu-susfs] [--ak3 yes|no] [--kernel-name "..."]
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

AK3_REPO="${AK3_REPO:-https://github.com/osm0sis/AnyKernel3.git}"
AK3_COMMIT="${AK3_COMMIT:-41f04bdb4ee30a44e429c2c1131d5e8bb32b15f1}"

KERNEL_DIR=""
DEVICE=""
OUT_DIR="$REPO_DIR/dist"
TAG="pe12-bakasu-susfs"
DO_AK3="yes"
KERNEL_NAME="Samsung Exynos 9810 - PE12 / ArrowOS 12.1"

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[x]\033[0m %s\n' "$*" >&2; exit 1; }

while [ $# -gt 0 ]; do
	case "$1" in
		--kernel-dir)  KERNEL_DIR="$2"; shift 2 ;;
		--device)      DEVICE="$2"; shift 2 ;;
		--out)         OUT_DIR="$2"; shift 2 ;;
		--tag)         TAG="$2"; shift 2 ;;
		--ak3)         DO_AK3="$2"; shift 2 ;;
		--kernel-name) KERNEL_NAME="$2"; shift 2 ;;
		-h|--help)     sed -n '2,16p' "$0"; exit 0 ;;
		*)             die "unknown argument: $1" ;;
	esac
done

[ -n "$KERNEL_DIR" ] || die "--kernel-dir is required"
[ -n "$DEVICE" ] || die "--device is required (starlte|star2lte|crownlte)"
case "$DEVICE" in
	starlte|star2lte|crownlte) ;;
	*) die "unsupported device '$DEVICE'" ;;
esac

BUILD_OUT="$KERNEL_DIR/out"
IMAGE="$BUILD_OUT/arch/arm64/boot/Image"
DTB_DIR="$BUILD_OUT/arch/arm64/boot/dts/exynos"
RAMDISK="$REPO_DIR/tools/pe12_ramdisk.cpio.gz"

[ -f "$IMAGE" ] || die "missing $IMAGE - build the kernel first"
[ -d "$DTB_DIR" ] || die "missing $DTB_DIR - build dtbs too (make Image dtbs)"
[ -f "$RAMDISK" ] || die "missing stock ramdisk $RAMDISK"

mkdir -p "$OUT_DIR"
OUT_DIR="$(cd "$OUT_DIR" && pwd)"

# ------------------------------------------------------------ boot images
log "Packaging boot images for $DEVICE"
python3 "$SCRIPT_DIR/mkbootimg.py" \
	--image "$IMAGE" --dtb-dir "$DTB_DIR" --device "$DEVICE" \
	--ramdisk "$RAMDISK" --out "$OUT_DIR" --tag "$TAG"

# ------------------------------------------------------------ AnyKernel3
if [ "$DO_AK3" = "yes" ]; then
	log "Building AnyKernel3 flashable zip"
	AK3_DIR="$(mktemp -d)"
	trap 'rm -rf "$AK3_DIR"' EXIT

	git clone --quiet "$AK3_REPO" "$AK3_DIR/ak3"
	( cd "$AK3_DIR/ak3" && git checkout --quiet "$AK3_COMMIT" )

	# We ship our own kernel + DT, everything else (ramdisk, cmdline, base)
	# is taken from the boot image already on the device by split_boot().
	cp -f "$OUT_DIR/Image-dtb"        "$AK3_DIR/ak3/Image-dtb"
	cp -f "$OUT_DIR/dt.img"           "$AK3_DIR/ak3/dt.img"
	cp -f "$OUT_DIR/dt.img"           "$AK3_DIR/ak3/dt"

	cat > "$AK3_DIR/ak3/anykernel.sh" <<AKEEOF
# AnyKernel3 configuration - generated by kernel-12l-mintmuffin
kernel.string=${KERNEL_NAME} (${TAG})
do.devicecheck=1
do.modules=0
do.systemless=1
do.cleanup=1
do.cleanuponabort=0
device.name1=starlte
device.name2=star2lte
device.name3=crownlte
device.name4=SM-G960F
device.name5=SM-G965F
device.name6=SM-N960F
block=/dev/block/platform/13500000.ufs/by-name/BOOT;
is_slot_device=0;
ramdisk_compression=auto;
patch_vbmeta_flag=auto;
. tools/ak3-core.sh;
split_boot;
flash_boot;
AKEEOF

	AK3_ZIP="anykernel3-${DEVICE}-${TAG}.zip"
	( cd "$AK3_DIR/ak3" && rm -f "$OUT_DIR/$AK3_ZIP" \
		&& zip -r9 -q "$OUT_DIR/$AK3_ZIP" . -x '.git*' 'README.md' '*placeholder' )
	log "$AK3_ZIP ($(du -h "$OUT_DIR/$AK3_ZIP" | cut -f1))"
fi

log "Artifacts in $OUT_DIR"
ls -l "$OUT_DIR"
